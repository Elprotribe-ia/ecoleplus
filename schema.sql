CREATE TABLE IF NOT EXISTS schools(id TEXT PRIMARY KEY, nom TEXT);
CREATE TABLE IF NOT EXISTS users(id TEXT PRIMARY KEY, school TEXT, nom TEXT, email TEXT UNIQUE, role TEXT, hash TEXT, salt TEXT, actif INTEGER DEFAULT 1, last INTEGER);
CREATE TABLE IF NOT EXISTS records(id TEXT PRIMARY KEY, school TEXT, type TEXT, data TEXT, t INTEGER, x INTEGER DEFAULT 0, st INTEGER);
CREATE INDEX IF NOT EXISTS ix_records ON records(school, st);
CREATE TABLE IF NOT EXISTS audit(id INTEGER PRIMARY KEY AUTOINCREMENT, school TEXT, uid TEXT, type TEXT, rid TEXT, x INTEGER, t INTEGER);
CREATE INDEX IF NOT EXISTS ix_audit ON audit(school, t);
